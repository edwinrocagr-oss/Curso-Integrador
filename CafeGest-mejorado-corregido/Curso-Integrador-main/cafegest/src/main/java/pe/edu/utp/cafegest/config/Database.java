    private Database() {}
    public static Connection open() throws SQLException {
        Properties config = loadConfig();
        String password = config.getProperty("db.password", "");
        if (password == null || password.isBlank()) {
            throw new SQLException("Configura db.password en src/main/resources/application-local.properties.");
        }
        String url = config.getProperty("db.url");
        String user = config.getProperty("db.user");
        return DriverManager.getConnection(url, user, password);
    }

    private static Properties loadConfig() throws SQLException {
        Properties config = new Properties();
        try (InputStream defaults = Database.class.getResourceAsStream("/application.properties")) {
            if (defaults == null) {
                throw new SQLException("No se encontró src/main/resources/application.properties.");
            }
            config.load(defaults);
        } catch (IOException e) {
            throw new SQLException("No se pudo leer application.properties.", e);
        }
        try (InputStream local = Database.class.getResourceAsStream("/application-local.properties")) {
            if (local != null) {
                config.load(local);
            }
        } catch (IOException e) {
            throw new SQLException("No se pudo leer application-local.properties.", e);
        }
        return config;
    }

    public static void init() throws SQLException {
        try (Connection c = open(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS usuarios (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario VARCHAR(60) UNIQUE NOT NULL, clave_hash VARCHAR(200) NOT NULL, rol VARCHAR(20) NOT NULL, activo BOOLEAN DEFAULT TRUE)");
            s.execute("CREATE TABLE IF NOT EXISTS productos (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(120) NOT NULL, categoria VARCHAR(80) NOT NULL, precio DECIMAL(12,2) NOT NULL CHECK(precio>=0), stock INTEGER NOT NULL CHECK(stock>=0), minimo INTEGER NOT NULL DEFAULT 5 CHECK(minimo>=0), activo BOOLEAN NOT NULL DEFAULT TRUE)");
            s.execute("CREATE TABLE IF NOT EXISTS ventas (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, usuario VARCHAR(60) NOT NULL, total DECIMAL(12,2) NOT NULL)");
            s.execute("CREATE TABLE IF NOT EXISTS venta_detalle (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, venta_id INTEGER NOT NULL REFERENCES ventas(id), producto_id INTEGER NOT NULL REFERENCES productos(id), cantidad INTEGER NOT NULL CHECK(cantidad>0), precio DECIMAL(12,2) NOT NULL)");
            s.execute("CREATE TABLE IF NOT EXISTS movimientos (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, producto_id INTEGER NOT NULL REFERENCES productos(id), fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP, tipo VARCHAR(30) NOT NULL, cantidad INTEGER NOT NULL, observacion VARCHAR(200))");
            s.execute("CREATE TABLE IF NOT EXISTS comandas (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, venta_id INTEGER REFERENCES ventas(id) ON DELETE SET NULL, mesa VARCHAR(120) NOT NULL DEFAULT 'Para llevar', pedido TEXT NOT NULL, estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','PREPARANDO','LISTO','ENTREGADO')), fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
            s.execute("ALTER TABLE comandas ADD COLUMN IF NOT EXISTS venta_id INTEGER REFERENCES ventas(id) ON DELETE SET NULL");
            s.execute("CREATE UNIQUE INDEX IF NOT EXISTS comandas_venta_id_unique ON comandas(venta_id) WHERE venta_id IS NOT NULL");
            // Catálogo de demostración: solo se carga si todavía no existen productos activos.
            try (ResultSet r = s.executeQuery("SELECT COUNT(*) FROM productos WHERE activo=TRUE")) {
                r.next();
                if (r.getInt(1) == 0) {
                    try (PreparedStatement p = c.prepareStatement("INSERT INTO productos(nombre,categoria,precio,stock,minimo) VALUES(?,?,?,?,?)")) {
                        for (DemoProduct item : DEMO_PRODUCTS) {
                            p.setString(1, item.nombre());
                            p.setString(2, item.categoria());
                            p.setBigDecimal(3, item.precio());
                            p.setInt(4, item.stock());
                            p.setInt(5, item.minimo());
                            p.addBatch();
                        }
                        p.executeBatch();
                    }
                }
            }
        }
    }
