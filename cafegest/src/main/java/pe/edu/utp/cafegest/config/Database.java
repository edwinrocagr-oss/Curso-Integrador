package pe.edu.utp.cafegest.config;

import java.sql.*;
import java.nio.file.*;

/** Fuente de conexiones y creación inicial del esquema. Por defecto usa H2 local. */
public final class Database {
    private Database() {}
    public static Connection open() throws SQLException {
        String url = System.getenv("CAFEGEST_DB_URL");
        if (url == null || url.isBlank()) {
            try { Files.createDirectories(Path.of(System.getProperty("user.home"), ".cafegest")); }
            catch (Exception e) { throw new SQLException("No se pudo crear el directorio de datos", e); }
            url = "jdbc:h2:file:" + Path.of(System.getProperty("user.home"), ".cafegest", "cafegest").toAbsolutePath() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE";
        }
        return DriverManager.getConnection(url, System.getenv().getOrDefault("CAFEGEST_DB_USER", "sa"), System.getenv().getOrDefault("CAFEGEST_DB_PASSWORD", ""));
    }
    public static void init() throws SQLException {
        try (Connection c = open(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS usuarios (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario VARCHAR(60) UNIQUE NOT NULL, clave_hash VARCHAR(200) NOT NULL, rol VARCHAR(20) NOT NULL, activo BOOLEAN DEFAULT TRUE)");
            s.execute("CREATE TABLE IF NOT EXISTS productos (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(120) NOT NULL, categoria VARCHAR(80) NOT NULL, precio DECIMAL(12,2) NOT NULL CHECK(precio>=0), stock INTEGER NOT NULL CHECK(stock>=0), minimo INTEGER NOT NULL DEFAULT 5 CHECK(minimo>=0), activo BOOLEAN NOT NULL DEFAULT TRUE)");
            s.execute("CREATE TABLE IF NOT EXISTS ventas (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, usuario VARCHAR(60) NOT NULL, total DECIMAL(12,2) NOT NULL)");
            s.execute("CREATE TABLE IF NOT EXISTS venta_detalle (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, venta_id INTEGER NOT NULL REFERENCES ventas(id), producto_id INTEGER NOT NULL REFERENCES productos(id), cantidad INTEGER NOT NULL CHECK(cantidad>0), precio DECIMAL(12,2) NOT NULL)");
            s.execute("CREATE TABLE IF NOT EXISTS movimientos (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, producto_id INTEGER NOT NULL REFERENCES productos(id), fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP, tipo VARCHAR(30) NOT NULL, cantidad INTEGER NOT NULL, observacion VARCHAR(200))");
        }
    }
}
